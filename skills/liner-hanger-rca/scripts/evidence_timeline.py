"""Retrospective evidence timeline: preserve facts, screening prompts and uncertainty.

This is a DATA product, not a playback UI and not an automatic root-cause
attribution. It does not modify source rig CSVs or assign timestamps to
day-level job-report events.
"""
from __future__ import annotations

from dataclasses import dataclass, asdict
from hashlib import sha256
from datetime import datetime, timezone
from typing import Mapping, Sequence

KINDS = {"reported_event", "measured_observation", "screening_candidate",
         "screening_context", "evidence_gap", "engineer_annotation"}
TIME_STATES = {"verified", "reported_approximate", "unknown"}
REVIEW_STATES = {"unreviewed", "review_requested", "engineer_reviewed"}


class TimelineError(ValueError):
    pass


def _required(value, field):
    if not isinstance(value, str) or not value.strip():
        raise TimelineError(f"{field}: required")
    return value.strip()


def _aware(raw):
    try:
        t = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except (AttributeError, ValueError):
        raise TimelineError("timestamp must be valid offset-aware ISO 8601") from None
    if t.tzinfo is None or t.utcoffset() is None:
        raise TimelineError("timestamp must contain UTC offset")
    return t.astimezone(timezone.utc)


@dataclass(frozen=True)
class EvidenceEvent:
    event_id: str
    case_id: str
    kind: str
    summary: str
    source_ids: tuple[str, ...]
    time_state: str
    timestamp: str | None = None
    time_basis: str | None = None
    review_status: str = "unreviewed"
    related_rule_id: str | None = None
    related_channel_id: str | None = None
    screening_status: str | None = None
    reasons: tuple[str, ...] = ()
    notes: str = ""
    source_sample_time: str | None = None
    screening_details: dict | None = None
    source_locations: dict | None = None
    measurement_details: dict | None = None

    def validate(self):
        _required(self.event_id, "event_id")
        _required(self.case_id, "case_id")
        _required(self.summary, "summary")
        if self.kind not in KINDS or self.time_state not in TIME_STATES:
            raise TimelineError("invalid kind/time_state")
        if self.review_status not in REVIEW_STATES:
            raise TimelineError("invalid review_status")
        if not self.source_ids or any(not isinstance(s, str) or not s.strip() for s in self.source_ids):
            raise TimelineError("at least one valid source ID is required")
        if self.time_state == "verified":
            if not self.timestamp:
                raise TimelineError("verified event requires a timestamp")
            _aware(self.timestamp)
            _required(self.time_basis, "time_basis")
        elif self.timestamp is not None:
            # An approximate string may be retained but must NEVER be ordered
            # as if independently time-zone-verified.
            _required(self.time_basis, "time_basis")
        return self

    def to_dict(self):
        return asdict(self)


def events_from_screen(case_id, limit, observation, result):
    """Build a provenance-linked candidate from the existing operating screen.

    The original screening output must be generated by screen(limit, obs).
    An unverifiable screen is retained as an evidence gap and is NOT sorted by
    recorded timestamp when clock alignment is unverified.
    """
    from operating_limit_screen import screen
    expected = screen(limit, observation)
    if expected != result:
        raise TimelineError("screening result does not match supplied source inputs")
    _required(case_id, "case_id")
    category = {"outside_screening_bounds": "screening_candidate",
                "within_screening_bounds": "screening_context",
                "unverifiable": "evidence_gap"}[result["status"]]
    clock_usable = (observation.clock_alignment_verified
                    and observation.measurement_equivalence_verified
                    and observation.units_verified
                    and observation.channel_mapping_verified
                    and result["status"] != "unverifiable")
    # A source clock alignment flag does not itself prove a timezone. Require
    # explicit offset-aware ISO timestamp before any verified chronological order.
    time_state = "unknown"
    timestamp = None
    basis = None
    if clock_usable:
        _aware(observation.timestamp)
        time_state = "verified"
        timestamp = observation.timestamp
        basis = "Case-reviewed source clock alignment; explicit timezone offset"
    status = result["status"]
    identity = "|".join((case_id, limit.rule_id, observation.source_id,
                         observation.channel_id, observation.timestamp))
    stable_id = sha256(identity.encode("utf-8")).hexdigest()[:16]
    event = EvidenceEvent(
        event_id=f"screen:{limit.rule_id}:{stable_id}",
        case_id=case_id,
        kind=category,
        summary=f"Retrospective {status.replace('_', ' ')} for {limit.parameter}; not a tool-state conclusion",
        source_ids=(limit.source_id, observation.source_id),
        time_state=time_state, timestamp=timestamp, time_basis=basis,
        related_rule_id=limit.rule_id,
        related_channel_id=observation.channel_id,
        screening_status=status,
        reasons=tuple(result["reasons"]),
        notes=result["conclusion"],
        source_sample_time=observation.timestamp,
        screening_details={
            "observed": str(observation.value),
            "observed_unit": observation.unit,
            "observed_domain": observation.measurement_domain,
            "observed_pressure_basis": observation.pressure_basis,
            "expected_domain": limit.measurement_domain,
            "expected_pressure_basis": limit.pressure_basis,
            "parameter": limit.parameter,
            "stage": limit.stage,
            "comparator": limit.comparator,
            "lower": str(limit.lower) if limit.lower is not None else None,
            "upper": str(limit.upper) if limit.upper is not None else None,
            "limit_unit": limit.unit,
            "comparison_permitted": result["status"] != "unverifiable",
        },
        source_locations={
            limit.source_id: {"location": limit.source_location,
                              "revision": limit.source_revision},
            observation.source_id: {"channel": observation.channel_id,
                                    "location": None, "revision": None},
        },
    )
    return event.validate()


def build_timeline(case_id: str, events: Sequence[EvidenceEvent]):
    """Ordered only for verified event times; all others remain unplaced."""
    _required(case_id, "case_id")
    seen = set()
    verified = []
    unplaced = []
    for event in events:
        event.validate()
        if event.case_id != case_id:
            raise TimelineError("event belongs to a different case")
        if event.event_id in seen:
            raise TimelineError("duplicate event ID")
        seen.add(event.event_id)
        if event.time_state == "verified":
            verified.append(event)
        else:
            unplaced.append(event)
    verified.sort(key=lambda e: (_aware(e.timestamp), e.event_id))
    # Not automatically a confirmed deviation: the earliest flagged screen is
    # only the earliest among eligible, reviewed-alignment comparison candidates.
    candidates = [e for e in verified if e.kind == "screening_candidate"]
    return {
        "case_id": case_id,
        "ordered_verified_events": [e.to_dict() for e in verified],
        "unplaced_events": [e.to_dict() for e in unplaced],
        "earliest_screening_candidate_id": candidates[0].event_id if candidates else None,
        "chronology_warning": (
            "Earliest SCREENING candidate among timestamp-verified, supplied events only; "
            "not necessarily the first operational deviation or cause. "
            "Approximate/unknown report events are not time-ordered."
        ),
        "investigation_conclusion": "undetermined",
    }


def event_from_dict(data: Mapping):
    try:
        cleaned = dict(data)
        for field in ("source_ids", "reasons"):
            if field in cleaned:
                cleaned[field] = tuple(cleaned[field])
        return EvidenceEvent(**cleaned).validate()
    except (TypeError, KeyError) as err:
        raise TimelineError(f"invalid evidence event: {err}") from err


def timeline_from_dict(case_id: str, raw_events):
    return build_timeline(case_id, [event_from_dict(e) for e in raw_events])
